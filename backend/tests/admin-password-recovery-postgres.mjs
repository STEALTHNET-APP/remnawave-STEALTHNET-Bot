import assert from 'node:assert/strict';
import bcrypt from 'bcryptjs';
const url = process.env.TEST_DATABASE_URL;
if (!url || !new URL(url).pathname.startsWith('/issue184_test_')) throw new Error('Use a disposable issue184_test_ database');
process.env.DATABASE_URL = url;
const { prisma } = await import('../dist/db.js');
const { resetAdminPassword, validateRecoveryPassword } = await import('../dist/modules/auth/reset-admin-password.js');
try {
  await prisma.$executeRawUnsafe('CREATE TABLE admins (id text PRIMARY KEY, email text UNIQUE NOT NULL, password_hash text NOT NULL, must_change_password boolean NOT NULL DEFAULT true, role text NOT NULL DEFAULT \'ADMIN\', allowed_sections text, totp_secret text, totp_enabled boolean NOT NULL DEFAULT false, created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP)');
  await prisma.$executeRawUnsafe('CREATE TABLE refresh_tokens (id text PRIMARY KEY, admin_id text NOT NULL, token text UNIQUE NOT NULL, expires_at timestamp NOT NULL, created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP)');
  await prisma.$executeRawUnsafe('CREATE TABLE admin_events (id text PRIMARY KEY, kind varchar(80) NOT NULL, actor_id varchar(120), actor_ip varchar(64), target_type varchar(40), target_id text, payload jsonb, created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP)');
  const oldHash = await bcrypt.hash('old-test-password', 4);
  const admin = await prisma.admin.create({ data: { email: 'recovery@example.invalid', passwordHash: oldHash, totpEnabled: true, totpSecret: 'keep-test-secret' } });
  const other = await prisma.admin.create({ data: { email: 'other@example.invalid', passwordHash: oldHash } });
  const manager = await prisma.admin.create({ data: { email: 'manager@example.invalid', role: 'MANAGER', passwordHash: oldHash } });
  const refresh = id => prisma.refreshToken.create({ data: { adminId: id, token: 'test-' + id, expiresAt: new Date(Date.now() + 60000) } });
  await refresh(admin.id); await refresh(other.id);
  assert.throws(() => validateRecoveryPassword('short'));
  assert.throws(() => validateRecoveryPassword('я'.repeat(37)));
  await assert.rejects(resetAdminPassword('missing@example.invalid', 'new-test-password'), /не найден/);
  await assert.rejects(resetAdminPassword(manager.email, 'new-test-password'), /не найден/);
  await resetAdminPassword(' RECOVERY@example.invalid ', 'new-test-password');
  const changed = await prisma.admin.findUnique({ where: { id: admin.id } });
  assert.ok(await bcrypt.compare('new-test-password', changed.passwordHash));
  assert.ok(!await bcrypt.compare('old-test-password', changed.passwordHash));
  assert.equal(changed.totpEnabled, true); assert.equal(changed.totpSecret, 'keep-test-secret');
  assert.equal(changed.role, 'ADMIN'); assert.equal(changed.mustChangePassword, false);
  assert.equal(await prisma.refreshToken.count({ where: { adminId: admin.id } }), 0);
  assert.equal(await prisma.refreshToken.count({ where: { adminId: other.id } }), 1);
  assert.equal((await prisma.admin.findUnique({ where: { id: other.id } })).passwordHash, oldHash);
  assert.equal((await prisma.admin.findUnique({ where: { id: manager.id } })).passwordHash, oldHash);
  const audit = await prisma.adminEvent.findFirst();
  assert.equal(audit.kind, 'admin.password_recovery');
  assert.ok(!JSON.stringify(audit).includes('new-test-password'));
  await refresh(admin.id);
  await prisma.$executeRawUnsafe('DROP TABLE admin_events');
  await assert.rejects(resetAdminPassword(admin.email, 'rollback-test-password'));
  assert.equal((await prisma.admin.findUnique({ where: { id: admin.id } })).passwordHash, changed.passwordHash);
  assert.equal(await prisma.refreshToken.count({ where: { adminId: admin.id } }), 1);
  console.log('PASS: password replacement, account isolation, 2FA preserved, refresh revocation, audit, transaction rollback');
} finally { await prisma.$disconnect(); }
