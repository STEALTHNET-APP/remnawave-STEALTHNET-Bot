import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import express from 'express';
import { PrismaClient } from '@prisma/client';

const url = process.env.TEST_DATABASE_URL;
if (!url || !new URL(url).pathname.startsWith('/issue76_test_')) throw Error('A disposable issue76_test_ database is required');
process.env.DATABASE_URL = url;
process.env.BOT_TOKEN = 'test-token-76';
const setup = new PrismaClient({ datasources: { db: { url } } });
await setup.$executeRawUnsafe('CREATE TABLE system_settings (id TEXT PRIMARY KEY, key TEXT UNIQUE NOT NULL, value TEXT NOT NULL)');
await setup.$executeRawUnsafe(await fs.readFile(new URL('../prisma/migrations/20261016220000_telegram_consent/migration.sql', import.meta.url), 'utf8'));
await setup.$disconnect();
const { prisma } = await import('../dist/db.js');
const { botTerms } = await import('../dist/modules/bot/terms.service.js');
const { botTermsRouter } = await import('../dist/modules/bot/terms.routes.js');
const app = express();
app.use(express.json(), botTermsRouter);
const server = app.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const request = (path, body, token = 'test-token-76') => fetch(`http://127.0.0.1:${server.address().port}${path}`, { method: 'POST', headers: { 'content-type': 'application/json', 'X-Telegram-Bot-Token': token }, body: JSON.stringify(body) });
try {
  assert.equal((await request('/status', { telegramId: '123' }, '')).status, 401);
  assert.equal((await request('/accept', { telegramId: '123', version: 'a'.repeat(32) }, 'wrong')).status, 401);
  for (const telegramId of ['0', '-1', '1.1', 'abc', '9007199254740992']) assert.equal((await request('/status', { telegramId })).status, 400);
  assert.equal((await request('/status', { telegramId: '123', pendingStart: '<bad>' })).status, 400);
  let state = await botTerms('123', {});
  assert.equal(state.required, false);
  assert.equal(await prisma.telegramConsent.count(), 0);
  for (const [key, value] of [['agreement_link', 'https://example.com/terms'], ['offer_link', 'https://example.com/offer'], ['refund_link', 'javascript:alert(1)']]) await prisma.systemSetting.create({ data: { key, value } });
  state = await (await request('/status', { telegramId: '123', pendingStart: 'ref_TEST' })).json();
  assert.equal(state.accepted, false);
  assert.equal(state.documents.length, 2);
  assert.equal((await request('/accept', { telegramId: '456', version: state.version })).status, 409);
  await botTerms('123', {});
  assert.equal((await prisma.telegramConsent.findUnique({ where: { telegramId: '123' } })).pendingStart, 'ref_TEST');
  await prisma.$disconnect();
  state = await botTerms('123', {});
  const results = await Promise.all(Array.from({ length: 8 }, () => botTerms('123', { acceptVersion: state.version })));
  assert.equal(results.filter(r => r.completed).length, 1);
  assert.equal(results.find(r => r.completed).pendingStart, 'ref_TEST');
  const stored = await prisma.telegramConsent.findUnique({ where: { telegramId: '123' } });
  assert.ok(stored.acceptedAt instanceof Date);
  assert.equal(stored.pendingStart, null);
  assert.equal(JSON.parse(stored.acceptedDocuments).length, 2);
  await prisma.$disconnect();
  assert.equal((await botTerms('123', {})).accepted, true);
  const other = await botTerms('456', {});
  assert.equal(other.accepted, false);
  await prisma.systemSetting.update({ where: { key: 'agreement_link' }, data: { value: 'https://example.com/new-terms' } });
  assert.equal((await request('/accept', { telegramId: '123', version: state.version })).status, 409);
  const changed = await botTerms('123', { pendingStart: 'gift_TEST' });
  assert.notEqual(changed.version, state.version);
  assert.equal(changed.accepted, false);
  const accepted = await botTerms('123', { acceptVersion: changed.version });
  assert.equal(accepted.pendingStart, 'gift_TEST');
  assert.equal(accepted.completed, true);
  await prisma.systemSetting.deleteMany();
  assert.equal((await botTerms('123', {})).required, false);
  await prisma.$executeRawUnsafe('DROP TABLE system_settings');
  assert.equal((await request('/status', { telegramId: '123' })).status, 503);
  console.log('PASS: real PostgreSQL migration, authentication, validation, document filtering, persistent consent and referral, reconnect, concurrent acceptance once, changed links, isolation, fail closed');
} finally {
  await new Promise(resolve => server.close(resolve));
  await prisma.$disconnect();
}
