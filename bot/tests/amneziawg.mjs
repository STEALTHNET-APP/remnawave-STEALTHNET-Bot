import assert from 'node:assert/strict';
import fs from 'node:fs';
import { InputFile } from 'grammy';
const source = fs.readFileSync(new URL('../dist/index.js', import.meta.url), 'utf8');
const start = source.indexOf('if (data.startsWith("singbox:conf:"))');
const end = source.indexOf('if (data === "menu:my_singbox")', start);
assert(start > 0 && end > start);
const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
const handler = new AsyncFunction('data', 'api', 'token', 'ctx', 'InputFile', 'Buffer', source.slice(start, end));
const files = [], messages = [];
let owned = [{ id: 'own-slot', protocol: 'AMNEZIAWG', subscriptionLink: '[Interface]\nPrivateKey = test\n' }];
const api = { getSingboxSlots: async token => { assert.equal(token, 'owner-session'); return { slots: owned }; } };
const ctx = { reply: async text => messages.push(text), replyWithDocument: async (file, options) => files.push({ file, options }) };
await handler('singbox:conf:own-slot', api, 'owner-session', ctx, InputFile, Buffer);
assert.equal(files.length, 1); assert(files[0].file instanceof InputFile); assert(files[0].file.filename.endsWith('.conf'));
await handler('singbox:conf:foreign-slot', api, 'owner-session', ctx, InputFile, Buffer);
owned = []; await handler('singbox:conf:own-slot', api, 'owner-session', ctx, InputFile, Buffer);
assert.equal(files.length, 1); assert.equal(messages.length, 2);
console.log('PASS: bot sends .conf for owned access only; missing/expired access rejected');
