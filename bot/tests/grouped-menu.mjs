import assert from 'node:assert/strict';
import {mainMenu, profileButtons} from '../dist/keyboard.js';
const base={showTrial:true,showVpn:true,showProxy:true,showSingbox:true,showExtraOptions:true,showGift:true,showTickets:true,hasSupportLinks:true,appUrl:'https://example.com',buttonsPerRow:2};
const buttons=m=>m.inline_keyboard.flat();
const callbacks=m=>buttons(m).map(b=>b.callback_data).filter(Boolean);
assert(callbacks(mainMenu(base)).includes('menu:tariffs'));
const grouped=mainMenu({...base,groupCabinet:true});
assert(callbacks(grouped).includes('menu:profile'));
assert(!callbacks(grouped).includes('menu:tariffs'));
assert(buttons(grouped).some(b=>b.web_app?.url==='https://example.com/cabinet'));
assert(callbacks(grouped).includes('menu:support'));
const children=mainMenu({...base,groupCabinet:true,section:'profile'});
assert(callbacks(children).includes('menu:tariffs'));
assert(callbacks(children).includes('menu:devices'));
assert(!callbacks(children).includes('menu:profile'));
const profile=profileButtons(null,undefined,undefined,false,'ru',children);
assert.equal(buttons(profile).at(-1).callback_data,'menu:main');
assert(callbacks(profile).includes('profile:lang'));
const config=[{id:'profile',visible:false,label:'Мой кабинет',order:0},{id:'tariffs',visible:false,label:'Hidden',order:1},{id:'devices',visible:true,label:'My devices',order:2,style:'danger'}];
assert(callbacks(mainMenu({...base,botButtons:config,groupCabinet:true,menuMode:'web'})).includes('menu:profile'));
assert.equal(config[0].visible,false);
const hidden=mainMenu({...base,botButtons:config,groupCabinet:true,section:'profile',menuMode:'web'});
assert(!buttons(hidden).some(b=>b.text==='Hidden'));
assert.equal(buttons(hidden).find(b=>b.text==='My devices').web_app.url,'https://example.com/cabinet/menu/devices');
assert.equal(buttons(hidden).find(b=>b.text==='My devices').style,'danger');
assert(!callbacks(mainMenu({...base,showTrial:false,section:'profile'})).includes('menu:trial'));
console.log('PASS: grouped navigation, Web cabinet, support, back, hidden buttons, custom labels, Web mode and immutable config');
