import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import * as keyboard from '../dist/keyboard.js';
const handlers = new Map();
let checkoutCalls = 0, paidCalls = 0, refundCalls = 0, fail = false;
const context = vm.createContext({ console });
const api = new vm.SyntheticModule(['getPublicConfig','starsCheckout','starsPaid','starsRefunded'], function () {
  this.setExport('getPublicConfig', async () => ({ supportLink: '' }));
  this.setExport('starsCheckout', async () => { checkoutCalls++; if (fail) throw Error('timeout'); });
  this.setExport('starsPaid', async () => { paidCalls++; return { delivery: 'delivered' }; });
  this.setExport('starsRefunded', async () => { refundCalls++; });
}, { context });
await api.link(() => {}); await api.evaluate();
const module = new vm.SourceTextModule(fs.readFileSync(new URL('../dist/stars.js', import.meta.url), 'utf8'), { context });
await module.link(() => api); await module.evaluate();
module.namespace.registerStarsPayments({ on: (name, handler) => handlers.set(name, handler), command: (name, handler) => handlers.set(name, handler) });
const answers = [], messages = [];
const ctx = { chat: { id: 123 }, from: { id: 123 }, preCheckoutQuery: { from: { id: 123 }, invoice_payload: 'snstars:test', currency: 'XTR', total_amount: 10 }, answerPreCheckoutQuery: async (ok) => answers.push(ok), reply: async text => messages.push(text) };
await handlers.get('pre_checkout_query')(ctx);
assert.equal(checkoutCalls, 1); assert.equal(paidCalls, 0); assert.equal(answers.at(-1), true);
fail = true; await handlers.get('pre_checkout_query')(ctx); assert.equal(answers.at(-1), false);
ctx.preCheckoutQuery.invoice_payload = 'unknown'; await handlers.get('pre_checkout_query')(ctx); assert.equal(checkoutCalls, 2); assert.equal(answers.at(-1), false);
ctx.message = { successful_payment: { invoice_payload: 'snstars:test', currency: 'XTR', total_amount: 10, telegram_payment_charge_id: 'charge' } };
await handlers.get('message:successful_payment')(ctx); assert.equal(paidCalls, 1); assert.match(messages.at(-1), /Покупка доступна/);
ctx.message.successful_payment.currency = 'RUB'; await handlers.get('message:successful_payment')(ctx); assert.equal(paidCalls, 1);
ctx.message = { refunded_payment: { invoice_payload: 'snstars:test', currency: 'XTR', total_amount: 10, telegram_payment_charge_id: 'charge' } };
await handlers.get('message:refunded_payment')(ctx); assert.equal(refundCalls, 1);
await handlers.get('paysupport')(ctx); assert.match(messages.at(-1), /поддержку/);
keyboard.setStarsPaymentsEnabled(true);
const topup = currency => keyboard.topupPaymentMethodButtons('100', [], undefined, undefined, undefined, { currency }).inline_keyboard.flat();
assert(topup('RUB').some(button => button.callback_data === 'topup_stars:100'));
assert(!topup('USD').some(button => button.callback_data === 'topup_stars:100'));
keyboard.setStarsPaymentsEnabled(false);
assert(!topup('RUB').some(button => button.callback_data === 'topup_stars:100'));
console.log('PASS Stars bot: checkout never credits, validation failure rejects, receipt confirms purchase, refund and support handlers');
