const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('src/lib/telegram-viewport.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
function setup(miniapp = true) {
  const calls = [], events = new Map(), domEvents = new Map(), viewportEvents = new Map(), dataset = {}, styles = new Map();
  let meta = 'width=device-width, initial-scale=1.0';
  const viewport = { height: 844, offsetTop: 0, scale: 1, addEventListener: (e, fn) => viewportEvents.set(e, fn) };
  const tg = { initData: miniapp ? 'test' : '', isFullscreen: false, ready: () => calls.push('ready'), expand: () => calls.push('expand'), disableVerticalSwipes() {}, requestFullscreen: () => calls.push('request'), exitFullscreen: () => calls.push('exit'), onEvent: (e, fn) => events.set(e, fn), safeAreaInset: { top: 24, bottom: 12, left: 0, right: 0 }, contentSafeAreaInset: { top: 40, bottom: 0, left: 0, right: 0 } };
  const out = {};
  vm.runInNewContext(js, { exports: out, window: { Telegram: { WebApp: tg }, innerHeight: 844, visualViewport: viewport, addEventListener() {} }, document: { documentElement: { dataset, style: { setProperty: (k, v) => styles.set(k, v) } }, querySelector: () => ({ setAttribute: (k, v) => { meta = v; } }), addEventListener: (e, fn) => domEvents.set(e, fn) } });
  return { out, tg, calls, events, domEvents, viewportEvents, dataset, styles, viewport, meta: () => meta };
}
const t = setup();
t.out.initTelegramViewport();
assert.deepEqual(t.calls, ['ready', 'expand']);
assert.equal(t.dataset.tgMiniapp, '1');
assert.match(t.meta(), /maximum-scale=1.0/);
assert.equal(t.styles.get('--app-tg-top'), '64px');
t.tg.isFullscreen = true;
t.events.get('fullscreenChanged')();
assert.equal(t.dataset.tgFullscreen, '1');
t.tg.safeAreaInset = { top: 0, bottom: 0, left: 44, right: 0 };
t.tg.contentSafeAreaInset.top = 32;
t.events.get('safeAreaChanged')();
assert.equal(t.styles.get('--app-tg-top'), '32px');
assert.equal(t.styles.get('--app-tg-left'), '44px');
const cleanup = t.out.enterAuroraFullscreen();
assert.equal(t.calls.at(-1), 'request');
cleanup();
assert.equal(t.calls.at(-1), 'exit');
t.tg.isFullscreen = false;
t.events.get('fullscreenChanged')();
assert.equal(t.dataset.tgFullscreen, undefined);
t.tg.isFullscreen = true;
t.events.get('fullscreenChanged')();
assert.equal(t.dataset.tgFullscreen, '1');
t.viewport.height = 360;
t.viewport.offsetTop = 60;
t.viewportEvents.get('resize')();
assert.equal(t.styles.get('--app-viewport-height'), '360px');
assert.equal(t.styles.get('--app-viewport-top'), '60px');
t.viewport.height = 844;
t.viewport.offsetTop = 0;
t.viewportEvents.get('resize')();
assert.equal(t.styles.get('--app-viewport-height'), '844px');
t.tg.viewportHeight = 420;
t.events.get('viewportChanged')();
assert.equal(t.styles.get('--app-viewport-height'), '420px');
t.tg.viewportHeight = undefined;
t.events.get('viewportChanged')();
let prevented = 0;
t.domEvents.get('touchmove')({ touches: [1], preventDefault: () => prevented++ });
assert.equal(prevented, 0);
t.domEvents.get('touchmove')({ touches: [1, 2], preventDefault: () => prevented++ });
assert.equal(prevented, 1);
t.domEvents.get('gesturestart')({ preventDefault: () => prevented++ });
assert.equal(prevented, 2);
t.out.initTelegramViewport();
assert.equal(t.calls.filter(x => x === 'ready').length, 1);
const browser = setup(false);
browser.out.initTelegramViewport();
assert.equal(browser.dataset.tgMiniapp, undefined);
assert.equal(browser.domEvents.size, 0);
assert.equal(browser.meta(), 'width=device-width, initial-scale=1.0');
browser.viewport.scale = 2;
browser.viewport.height = 422;
browser.viewportEvents.get('resize')();
assert.equal(browser.styles.get('--app-viewport-height'), '844px');
const legacy = setup();
legacy.tg.requestFullscreen = () => { throw Error('unsupported'); };
legacy.out.initTelegramViewport();
legacy.out.enterAuroraFullscreen()();
assert.equal(legacy.dataset.tgFullscreen, undefined);
console.log('PASS: fullscreen transitions, layout switching, rotation insets, keyboard open/close, pinch prevention, normal scrolling, browser zoom, legacy clients');
